# Microatividade 2: if, elif e else

tempoExperiencia = 5

if tempoExperiencia < 2:
    print('Nível de conhecimento júnior.')
elif tempoExperiencia > 2 and tempoExperiencia < 5:
    print('Nível de conhecimento pleno.')
else:
    print('Nível de conhecimento sênior.')

